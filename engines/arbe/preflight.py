"""Deterministic CR60/arbe environment and runtime preflight.

This module deliberately performs read-only discovery only. It does not
checkout branches, change configuration, compile, start ROS, attach GDB, or
stop processes. The public result is an auditable arbe-preflight.v1 payload
which later runtime/build providers can consume.

The command runner is intentionally injected. Production uses an allowlisted
SSH runner; tests use a fake runner. No Pi/LLM text is executed as a shell
command by this module.
"""
