def test_trace_variable_chains_corrupt_meta_falls_through(tmp_path: Path) -> None:
    """Corrupted meta.json is treated as cache miss (fall through to full scan)."""
    from engines.signal_mapper import trace_variable_chains

    source_root = _write_source_tree(tmp_path / "src")
    docs_dir = tmp_path / "source_docs"

    trace_variable_chains(source_root, docs_dir)
    # Corrupt the meta file
    (docs_dir / "variable_chains.meta.json").write_text(
        "{not valid json", encoding="utf-8"
    )
    # Should NOT raise; should rescan and rewrite meta
    result = trace_variable_chains(source_root, docs_dir)
    assert "struct_aliases" in result
    meta = json.loads(
        (docs_dir / "variable_chains.meta.json").read_text(encoding="utf-8")
    )
    assert "file_hashes" in meta  # rewritten


