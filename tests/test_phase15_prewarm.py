def test_trace_variable_chains_writes_meta_cache(tmp_path: Path) -> None:
    """First call writes both variable_chains.json and variable_chains.meta.json."""
    from engines.signal_mapper import trace_variable_chains

    source_root = _write_source_tree(tmp_path / "src")
    docs_dir = tmp_path / "source_docs"

    result = trace_variable_chains(source_root, docs_dir)
    assert "struct_aliases" in result

    cache_path = docs_dir / "variable_chains.json"
    meta_path = docs_dir / "variable_chains.meta.json"
    assert cache_path.exists(), "variable_chains.json should be written"
    assert meta_path.exists(), "variable_chains.meta.json should be written"

    meta = json.loads(meta_path.read_text(encoding="utf-8"))
    assert "file_hashes" in meta
    assert meta.get("version") == 1
    assert meta.get("alias_count") == len(result.get("struct_aliases", {}))
    assert meta.get("rte_file", "").endswith("RteComMapping.c")
    # Every scanned source file should have a hash entry.
    assert len(meta["file_hashes"]) >= 1


def test_trace_variable_chains_cache_hit_on_unchanged(tmp_path: Path) -> None:
    """Second call with unchanged source files returns cached result (no rescan)."""
    from ai import signal_mapper

    source_root = _write_source_tree(tmp_path / "src")
    docs_dir = tmp_path / "source_docs"

    # First call — full scan + write
    first = signal_mapper.trace_variable_chains(source_root, docs_dir)
    first_meta = json.loads(
        (docs_dir / "variable_chains.meta.json").read_text(encoding="utf-8")
    )

    # Patch _extract_rte_write_prefixes to detect if rescan runs.
    call_count = {"n": 0}
    real_extract = signal_mapper._extract_rte_write_prefixes

    def counted(rte_path):
        call_count["n"] += 1
        return real_extract(rte_path)

    signal_mapper._extract_rte_write_prefixes = counted
    try:
        second = signal_mapper.trace_variable_chains(source_root, docs_dir)
    finally:
        signal_mapper._extract_rte_write_prefixes = real_extract

    # Cache hit → should NOT have called _extract_rte_write_prefixes (file is unchanged).
    assert call_count["n"] == 0, "Cache hit should skip file reads"
    assert second == first, "Cached result should match the original"

    # Meta should be unchanged (same file hashes).
    second_meta = json.loads(
        (docs_dir / "variable_chains.meta.json").read_text(encoding="utf-8")
    )
    assert second_meta["file_hashes"] == first_meta["file_hashes"]


def test_trace_variable_chains_invalidation_on_change(tmp_path: Path) -> None:
    """Changing a scanned source file invalidates the cache and triggers rescan."""
    from ai import signal_mapper

    source_root = _write_source_tree(tmp_path / "src")
    docs_dir = tmp_path / "source_docs"

    signal_mapper.trace_variable_chains(source_root, docs_dir)
    first_meta = json.loads(
        (docs_dir / "variable_chains.meta.json").read_text(encoding="utf-8")
    )

    # Mutate one of the scanned files
    gv_file = (
        source_root / "coem" / "GWM_B26" / "components" / "AswPerception" / "func"
        / "globalVariDef.c"
    )
    gv_file.write_text(_GLOBAL_VAR_DEF + "\n// extra line\n", encoding="utf-8")

    # Second call should detect hash mismatch and rescan
    call_count = {"n": 0}
    real_extract = signal_mapper._extract_rte_write_prefixes

    def counted(rte_path):
        call_count["n"] += 1
        return real_extract(rte_path)

    signal_mapper._extract_rte_write_prefixes = counted
    try:
        signal_mapper.trace_variable_chains(source_root, docs_dir)
    finally:
        signal_mapper._extract_rte_write_prefixes = real_extract

    assert call_count["n"] >= 1, "File change should trigger a rescan"

    second_meta = json.loads(
        (docs_dir / "variable_chains.meta.json").read_text(encoding="utf-8")
    )
    # The hash for the modified file MUST change.
    gv_rel = (
        "coem\\GWM_B26\\components\\AswPerception\\func\\globalVariDef.c"
    )
    assert second_meta["file_hashes"][gv_rel] != first_meta["file_hashes"][gv_rel]


