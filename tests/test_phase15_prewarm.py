def test_run_prewarm_writes_meta_json(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """``_run_prewarm`` writes ``prewarm_meta.json`` containing elapsed_sec + ops."""
    # Patch CodeLearner at its source module (cli imports it lazily inside _run_prewarm).
    import ai.code_learner as _cl_mod

    source_root = _write_source_tree(tmp_path / "src")
    docs_dir = tmp_path / "source_docs" / "gen6_gwm_b26"
    docs_dir.mkdir(parents=True, exist_ok=True)

    config = {
        "paths": {
            "source_code": str(source_root),
            "source_docs": str(docs_dir),
        },
        "project": {"source_docs_dir": str(docs_dir)},
        "identity": {"variant_id": "gen6/gwm_b26"},
    }

    class _StubRouter:
        pass

    monkeypatch.setattr("cli.get_router", lambda cfg: _StubRouter())

    class _StubLearner:
        def __init__(self, router, cfg, root):
            pass

        def learn(self, status_cb=None, force_pairs=None, force_constants=False):
            return {"learned_count": 0, "skipped_count": 0, "error_count": 0}

        def ensure_overview_docs(self, funcs=None, force=False, status_cb=None):
            return {"generated": [], "skipped": list(funcs or []), "failed": [],
                    "reason": "all_up_to_date"}

    monkeypatch.setattr(_cl_mod, "CodeLearner", _StubLearner)

    from cli import _run_prewarm
    summary = _run_prewarm(config=config, force=False)

    meta_path = docs_dir / "prewarm_meta.json"
    assert meta_path.exists(), "prewarm_meta.json should be written"
    meta = json.loads(meta_path.read_text(encoding="utf-8"))
    assert "operations" in meta
    assert "elapsed_sec" in meta
    assert meta["force"] is False
    # trace_variable_chains was actually called → variable_chains.json exists
    assert (docs_dir / "variable_chains.json").exists()


